#!/usr/bin/env python3
"""tools/teleop/real_config.py — the real gamepad teleop config for drone_1 or drone_2, rendered from the ONE source
teleop_real_ours.yaml by exact text replacement (never a yaml load-and-dump), checked line by line and semantically.

  python3 real_config.py render --drone drone_2 --source <teleop_real_ours.yaml> --out <file>   (prints the operator block)
  python3 real_config.py check-drone drone_2

Exit: 0 done · 1 refused (the source drifted from the anchors, or the check failed) · 2 usage or unknown drone.
"""
import argparse, datetime, hashlib, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pad_core as P

try:
    import yaml
except ImportError:                    # verify_render refuses without it
    yaml = None

KNOWN_DRONES = ("drone_1", "drone_2")
CONTAINER_DIR = "/tmp/svg_real"
SOURCE_NAME = "teleop_real_ours.yaml"
NAMES = '    drone_names: ["%s"]'
TELEOP = '    teleop_drones: "%s"'
CONTROLLER = '    teleop_controller: "%s"'
ADDED_KEYS = ("led_controller", "joy_node")
HEADER_LINES = 2


class RenderError(Exception):
    pass


def check_drone(drone):
    if drone not in KNOWN_DRONES:
        raise RenderError("unknown drone %r — use drone_1 or drone_2" % (drone,))
    return drone


def sha256_text(text):
    return hashlib.sha256(text.encode()).hexdigest()


def container_path(drone):
    return "%s/teleop_real_%s.yaml" % (CONTAINER_DIR, check_drone(drone))


# (source line, required count): the only lines a render may change
ANCHORS = ((NAMES % "drone_1", 2), (TELEOP % "drone_1", 1), (CONTROLLER % "dragonrise_usb", 1))


def tail(drone, spec):
    return ['led_controller:', '  ros__parameters:', '    drone_names: ["%s"]' % drone,
            'joy_node:', '  ros__parameters:', '    device_name: "%s"' % spec.sdl_name]


def _code(line):
    return line.split("#", 1)[0]


def _replacement(line, drone, spec):
    """The rendered line for an anchor line, else None."""
    if line == NAMES % "drone_1":
        return NAMES % drone
    if line == TELEOP % "drone_1":
        return TELEOP % drone
    if line == CONTROLLER % "dragonrise_usb":
        return CONTROLLER % spec.profile
    return None


def _check_source(src_lines):
    for a, n in ANCHORS:
        got = sum(1 for l in src_lines if l == a)
        if got != n:
            raise RenderError("source drift: %r appears %d time(s), expected %d" % (a.strip(), got, n))
    for l in src_lines:
        for k in ADDED_KEYS:
            if l.startswith(k + ":"):
                raise RenderError("the source already has a top-level %s block" % k)


def render(src_text, drone, spec, now, src_sha):
    """The per-drone config text; RenderError on an unknown drone or any drift from the anchors."""
    check_drone(drone)
    src_lines = src_text.splitlines()
    _check_source(src_lines)
    body = [_replacement(l, drone, spec) or l for l in src_lines]
    if drone != "drone_1":
        stray = [i + 1 for i, l in enumerate(body) if "drone_1" in _code(l)]
        if stray:
            raise RenderError("source line(s) %s still name drone_1 after the %s render" % (stray, drone))
    header = ["# GENERATED by tools/real.sh teleop %s from %s (sha256 %s) — do not edit; re-run the command."
              % (drone, SOURCE_NAME, src_sha),
              "# drone %s · pad %s (%s, profile %s) · made %s" % (drone, spec.name, spec.sdl_name, spec.profile,
                                                                   now.isoformat(timespec="seconds"))]
    out = "\n".join(header + body + tail(drone, spec)) + "\n"
    verify_render(src_text, out, drone, spec)
    return out


def verify_render(src_text, out_text, drone, spec):
    """(a) line level: only the anchor lines differ, each by its expected replacement; (b) semantic: the yaml trees are
    equal once the listed keys are popped, and the top level gained exactly led_controller and joy_node."""
    if yaml is None:
        raise RenderError("PyYAML missing on the host — pip install pyyaml (the render cannot be checked)")
    check_drone(drone)
    s, o = src_text.splitlines(), out_text.splitlines()
    t = tail(drone, spec)
    if len(o) != HEADER_LINES + len(s) + len(t) or not all(l.startswith("# ") for l in o[:HEADER_LINES]):
        raise RenderError("rendered file has the wrong shape (header, body or appended blocks)")
    if o[-len(t):] != t:
        raise RenderError("appended blocks differ from the expected led_controller / joy_node blocks")
    body = o[HEADER_LINES:HEADER_LINES + len(s)]
    want = {i for i, l in enumerate(s) if _replacement(l, drone, spec) not in (None, l)}
    differ = {i for i, (a, b) in enumerate(zip(s, body)) if a != b}
    if differ != want:
        raise RenderError("lines %s differ, expected exactly %s" % (sorted(i + 1 for i in differ), sorted(i + 1 for i in want)))
    for i in differ:
        if body[i] != _replacement(s[i], drone, spec):
            raise RenderError("line %d is %r, expected %r" % (i + 1, body[i], _replacement(s[i], drone, spec)))
    try:
        ys, yo = yaml.safe_load(src_text), yaml.safe_load(out_text)
    except yaml.YAMLError as e:
        raise RenderError("yaml does not load: %s" % e)
    if set(yo) != set(ys) | set(ADDED_KEYS) or set(ys) & set(ADDED_KEYS):
        raise RenderError("top-level keys %s, expected the source's plus %s" % (sorted(yo), list(ADDED_KEYS)))
    expect = {("swarm_commander", "drone_names"): [drone], ("swarm_commander", "teleop_drones"): drone,
              ("mocap_bridge", "drone_names"): [drone], ("safe_teleop", "teleop_controller"): spec.profile}
    for (node, key), v in expect.items():
        got = yo[node]["ros__parameters"].pop(key, None)
        ys[node]["ros__parameters"].pop(key, None)
        if got != v:
            raise RenderError("%s.%s = %r, expected %r" % (node, key, got, v))
    if yo.pop("led_controller") != {"ros__parameters": {"drone_names": [drone]}}:
        raise RenderError("led_controller block is not drone_names [%s]" % drone)
    if yo.pop("joy_node") != {"ros__parameters": {"device_name": spec.sdl_name}}:
        raise RenderError("joy_node block is not device_name %r" % spec.sdl_name)
    if yo != ys:
        raise RenderError("a value outside the listed keys differs from the source")


def _section(lines, i):
    for j in range(i, -1, -1):
        l = lines[j]
        if l and not l[0].isspace() and not l.startswith("#") and l.rstrip().endswith(":"):
            return l.rstrip()[:-1]
    return "?"


def diff_summary(src_text, out_text):
    """The operator's view of the render: each changed source line, then the two added blocks."""
    s, o = src_text.splitlines(), out_text.splitlines()
    body = o[HEADER_LINES:HEADER_LINES + len(s)]
    out = []
    for i, (a, b) in enumerate(zip(s, body)):
        if a != b:
            out.append("  line %-4d %-18s %s  →  %s" % (i + 1, "(%s)" % _section(s, i), a.strip(), b.strip()))
    rest = o[HEADER_LINES + len(s):]
    blocks, cur = [], None
    for l in rest:
        if l and not l[0].isspace():
            cur = [l.rstrip(":")]; blocks.append(cur)
        elif cur is not None and l.strip() and l.strip() != "ros__parameters:":
            cur.append(l.strip())
    for b in blocks:
        out.append("  added     %-18s %s" % ("(%s)" % b[0], "; ".join(b[1:])))
    return out


def takeoff_point(src_text, drone):
    """(x, y, z) the drone takes off to: the source's hover_positions, slot of `drone` (the render's slot 0 for a
    one-drone source whose single name the render replaces)."""
    if yaml is None:
        raise RenderError("PyYAML missing on the host — pip install pyyaml")
    check_drone(drone)
    p = yaml.safe_load(src_text)["swarm_commander"]["ros__parameters"]
    names, hp = list(p["drone_names"]), [float(v) for v in p["hover_positions"]]
    if drone in names:
        i = names.index(drone)
    elif len(names) == 1:
        i = 0
    else:
        raise RenderError("cannot place %s: the source flies %s" % (drone, names))
    if len(hp) < 3 * (i + 1):
        raise RenderError("hover_positions has no point for %s" % drone)
    return tuple(hp[3 * i:3 * i + 3])


def takeoff_sentence(drone, point):
    return "Stand %s on x %s, y %s, nose toward +x. Takeoff flies a straight line to that point." % (
        check_drone(drone), point[0], point[1])


def pane_lines(drone, path):
    check_drone(drone)
    n = int(drone.split("_")[1])
    return ['laptop : cd ~/AirStack-starling-max2 && MOCAP_BODIES="%s" ./mocap.sh' % drone,
            'pane 1 : MicroXRCEAgent udp4 -p 8888 -v4',
            'pane 2 : ros2 launch svg_ground_control real_interfaces.launch.py drones:=%s target_systems:=%d' % (drone, n),
            'pane 3 : ros2 launch svg_ground_control ground_control.launch.py config:=%s use_mocap:=true use_foxglove_studio:=true' % path,
            'pane 5 : ros2 launch svg_ground_control teleop.launch.py config:=%s' % path]


def operator_block(src_text, out_text, drone, path):
    """What `tools/real.sh teleop drone_1` (or drone_2) prints after a PASS: diff, takeoff point, pane lines, reminder."""
    pt = takeoff_point(src_text, drone)
    return (["", "Config for %s: %s in the robot container. Only these lines differ from %s:" % (drone, path, SOURCE_NAME)]
            + diff_summary(src_text, out_text)
            + ["", "Takeoff point (hover_positions in %s): x %s, y %s, z %s" % (SOURCE_NAME, pt[0], pt[1], pt[2]),
               takeoff_sentence(drone, pt),
               "", "Commands, one per pane:"]
            + pane_lines(drone, path)
            + ["", "Do not press MODE. Re-run this command after any container restart or pad replug."])


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("render")
    r.add_argument("--drone", required=True)
    r.add_argument("--source", required=True)
    r.add_argument("--out", required=True)
    c = sub.add_parser("check-drone")
    c.add_argument("drone")
    a = ap.parse_args(argv)
    try:
        check_drone(a.drone)
    except RenderError as e:
        print("error: %s" % e, file=sys.stderr)
        return 2
    if a.cmd == "check-drone":
        return 0
    try:
        with open(a.source) as f:
            src = f.read()
        out = render(src, a.drone, P.F310, datetime.datetime.now().astimezone(), sha256_text(src))
        block = operator_block(src, out, a.drone, container_path(a.drone))
    except (OSError, RenderError, KeyError, TypeError, ValueError) as e:
        print("error: render refused — %s" % e, file=sys.stderr)
        return 1
    with open(a.out, "w") as f:
        f.write(out)
    print("\n".join(block))
    return 0


if __name__ == "__main__":
    sys.exit(main())
